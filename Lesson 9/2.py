import re


def replace_fio_with_N(text):
    """
    Заменяет ФИО в тексте на букву N.
    ФИО определяется по шаблону: каждое слово с заглавной буквы,
    фамилия может быть двойной (с дефисом).
    """
    # Регулярное выражение для поиска ФИО
    # Ищем последовательности из 2-3 слов, начинающихся с заглавной буквы
    # с возможным дефисом в первом слове (фамилии)
    pattern = r'\b([А-ЯЁ][а-яё]*(?:-[А-ЯЁ][а-яё]*)?)\s+([А-ЯЁ][а-яё]*)\s+([А-ЯЁ][а-яё]*)\b'

    # Заменяем все найденные ФИО на N
    result = re.sub(pattern, 'N', text)
    return result


# Входной текст
input_text = """Подсудимая Эверт-Колокольцева Елизавета Александровна
в судебном заседании вину инкриминируемого
правонарушения признана в полном объёме и суду показала,
что 14 сентября 1876 года, будучи в состояние алкогольного
опьянения от безысходности, в связи с состояние здоровья
позвонила со своего стационарного телефона в полицию,
сообщив о том, что у она в Предполагается заложена бомба.
После чего приехали сотрудники полиции, как можно скорее
и пожарные, которым она сообщила, что бомба — это она"""

print("Исходный текст:")
print(input_text)
print("\nТекст после замены ФИО:")
print(replace_fio_with_N(input_text))